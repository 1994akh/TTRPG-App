/**
 * npm run build:
 * 1. module/rules-data.mjs: the rules JSON as an ES module the runtime imports (so data models are synchronous).
 * 2. src/packs/**: JSON sources for the rules, races, classes, professions, signatures and spells compendia.
 * 3. packs/**: those compiled to LevelDB.
 */
import fs from "node:fs";
import path from "node:path";
import { compilePack } from "@foundryvtt/foundryvtt-cli";
import { id } from "./ids.mjs";
import { rulesPages } from "./rules-journal.mjs";
import { cleanSource, loadRules, ROOT, stats, writeSource } from "./util.mjs";

const c = loadRules();

// 1. Rules data module.
const header = "// Generated by build/build.mjs from data/rules/*.json. Do not edit.\n";
fs.writeFileSync(path.join(ROOT, "module/rules-data.mjs"), `${header}export const RULES = ${JSON.stringify(c)};\n`);

const IMG = {
  race: "icons/svg/mystery-man.svg", class: "icons/svg/sword.svg", profession: "icons/svg/hammer.svg",
  signature: "icons/svg/lightning.svg", spell: "icons/svg/aura.svg", rules: "icons/svg/book.svg"
};

function item(type, entry, system) {
  return {
    _id: id(`${type}:${entry.id}`), name: entry.name, type, img: IMG[type], system, effects: [], folder: null,
    sort: 0, ownership: { default: 0 }, flags: {}, _stats: stats(), _key: ""
  };
}

const packs = {
  races: c.races.map(r => item("race", r, { ruleId: r.id })),
  classes: c.classes.map(n => item("class", n, { ruleId: n.id })),
  professions: c.professions.map(n => item("profession", n, { ruleId: n.id })),
  signatures: c.signatures.map(s => item("signature", s, {
    line: s.line, tier: s.tier, grade: s.grade, points: s.points, cost: s.cost, effect: s.effect
  })),
  spells: c.spells.map(s => item("spell", s, {
    tradition: s.tradition, tier: s.tier, grade: s.grade, points: s.points, actions: String(s.actions),
    range: s.range ?? "", save: s.save ?? "", effect: s.effect
  }))
};

// Sort compendium entries by grade, then name, so F-grade nodes come first.
const GRADE_ORDER = "FEDCBAS";
const SOURCE = { races: c.races, classes: c.classes, professions: c.professions };
const gradeOf = (pack, doc) => doc.system.grade ?? SOURCE[pack]?.find(e => e.id === doc.system.ruleId)?.grade ?? "F";
for ( const [pack, list] of Object.entries(packs) ) {
  list.sort((a, b) => (GRADE_ORDER.indexOf(gradeOf(pack, a)) - GRADE_ORDER.indexOf(gradeOf(pack, b))) || a.name.localeCompare(b.name));
  list.forEach((doc, i) => { doc.sort = (i + 1) * 100; doc._key = `!items!${doc._id}`; });
}

const journalId = id("journal:rules");
const journal = {
  _id: journalId, name: "Rules of Possibilities", folder: null, sort: 0, flags: {}, categories: [],
  ownership: { default: 2 }, _stats: stats(), _key: `!journal!${journalId}`,
  pages: rulesPages(c).map((p, i) => {
    const pid = id(`journal:rules:${i}`);
    return {
      _id: pid, name: p.name, type: "text", title: { show: true, level: 1 }, sort: (i + 1) * 100,
      text: { format: 1, content: p.content.replace(/\n\s+/g, " ") }, ownership: { default: -1 }, flags: {},
      category: null, image: {}, video: { controls: true, volume: 0.5 }, src: null, system: {}, _stats: stats(),
      _key: `!journal.pages!${journalId}.${pid}`
    };
  })
};

for ( const dir of [...Object.keys(packs), "rules"] ) cleanSource(dir);
for ( const [dir, docs] of Object.entries(packs) ) for ( const doc of docs ) writeSource(dir, doc);
writeSource("rules", journal);

for ( const dir of [...Object.keys(packs), "rules"] ) {
  const dest = path.join(ROOT, "packs", dir);
  fs.rmSync(dest, { recursive: true, force: true });
  await compilePack(path.join(ROOT, "src/packs", dir), dest, { log: false });
}

console.log(`rules-data.mjs written; packs: ${Object.entries(packs).map(([k, v]) => `${k} ${v.length}`).join(", ")}, `
  + `rules journal ${journal.pages.length} pages`);
